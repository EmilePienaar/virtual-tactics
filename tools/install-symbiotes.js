/* Install the built symbiotes into TaleSpire, without eating anyone's data.

     node tools/install-symbiotes.js            update whatever is out of date
     node tools/install-symbiotes.js --check    say what would change, change nothing
     node tools/install-symbiotes.js --prune    also remove build files we no longer ship
     node tools/install-symbiotes.js --to "D:/path/to/Symbiotes"

   WHY THIS IS NOT `xcopy /s`
   --------------------------
   A symbiote folder is not only the symbiote. TaleSpire keeps the player's
   saved characters in `.localStorage` INSIDE it, and the folder is also where a
   connected 5etools `data/` directory and any imported `homebrew/` end up. So
   the obvious install - delete the folder, copy the new one - throws away every
   character at the table and the data set they were built from.

   This copies file by file and only what has actually changed, comparing
   contents rather than timestamps. Anything it did not build, it does not
   touch: `data/`, `.localStorage`, `.debug` and any stray file are left exactly
   where they are.

   WHAT COUNTS AS OUT OF DATE
   --------------------------
   A byte difference. Not a version string - the manifest's version is written
   by hand and would sit at 1.0 through a hundred real changes - and not a
   modification time, which a copy or a checkout resets for reasons that have
   nothing to do with content.

   PRUNING
   -------
   Off by default, and narrower than it looks: only `srd/`, every file of which
   is generated. A file dropped from the build lingers there and can still be
   loaded, so it is worth being able to clear.

   `homebrew/` is NOT pruned even though the build writes into it, because the
   player imports their own supplements beside the bundled one. Nothing outside
   `srd/` is ever removed, and `data/`, `.localStorage` and `.debug` are never
   touched at all.

   Zero dependencies. */
'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const SYMBIOTES = ['tale-sheet', 'tale-shop'];

/* Folders the build owns OUTRIGHT, and may therefore prune.

   Only `srd/`. Every file in it is generated by tools/extract-srd.js, so one
   the build no longer produces is genuinely dead.

   `homebrew/` is deliberately NOT here even though the build writes into it.
   It is a shared space: the build drops a converted supplement there, and the
   player imports their own beside it. Pruning it removes the player's - which
   this tool did until a test put a homebrew file in the sandbox and watched
   --prune eat it. */
const BUILD_OWNED = ['srd'];

/* Never touched, whatever the flags say. */
const SACRED = ['.localStorage', '.debug', 'data'];

const ARGS = process.argv.slice(2);
const CHECK = ARGS.includes('--check') || ARGS.includes('--dry-run');
const PRUNE = ARGS.includes('--prune');
const TO = (() => {
  const i = ARGS.indexOf('--to');
  return i >= 0 ? ARGS[i + 1] : null;
})();

/* ---- finding TaleSpire ------------------------------------------------- */

/* The install lives under the game's own data directory, which differs by
   platform and by whether the user moved it. Candidates are probed rather than
   assumed, and --to overrides the lot. */
function candidates() {
  const home = os.homedir();
  const out = [];
  if (TO) return [TO];
  if (process.platform === 'win32') {
    const appData = process.env.APPDATA || path.join(home, 'AppData', 'Roaming');
    const localLow = path.join(path.dirname(appData), 'LocalLow');
    out.push(path.join(localLow, 'BouncyRock Entertainment', 'TaleSpire', 'Symbiotes'));
  } else if (process.platform === 'darwin') {
    out.push(path.join(home, 'Library', 'Application Support',
      'BouncyRock Entertainment', 'TaleSpire', 'Symbiotes'));
    out.push(path.join(home, 'Library', 'Application Support', 'TaleSpire', 'Symbiotes'));
  }
  /* a Proton / Steam-on-Linux layout, and the odd manual install */
  out.push(path.join(home, '.steam', 'steam', 'steamapps', 'compatdata', '720620',
    'pfx', 'drive_c', 'users', 'steamuser', 'AppData', 'LocalLow',
    'BouncyRock Entertainment', 'TaleSpire', 'Symbiotes'));
  return out;
}

function findSymbiotesDir() {
  for (const c of candidates()) {
    if (fs.existsSync(c) && fs.statSync(c).isDirectory()) return c;
  }
  return null;
}

/* ---- comparing ---------------------------------------------------------- */

function walk(dir, base) {
  base = base || dir;
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const st = fs.statSync(full);
    if (st.isDirectory()) out.push(...walk(full, base));
    else out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out;
}

function hash(file) {
  return crypto.createHash('sha1').update(fs.readFileSync(file)).digest('hex');
}

function same(a, b) {
  if (!fs.existsSync(b)) return false;
  const sa = fs.statSync(a), sb = fs.statSync(b);
  if (sa.size !== sb.size) return false;      /* cheap reject before hashing */
  return hash(a) === hash(b);
}

/* ---- installing --------------------------------------------------------- */

function plan(name, destRoot) {
  const from = path.join(DIST, name);
  const to = path.join(destRoot, name);
  if (!fs.existsSync(from)) return { name, missingBuild: true };

  const built = walk(from);
  const add = [], update = [], keep = [];
  for (const rel of built) {
    const src = path.join(from, rel);
    const dst = path.join(to, rel);
    if (!fs.existsSync(dst)) add.push(rel);
    else if (!same(src, dst)) update.push(rel);
    else keep.push(rel);
  }

  /* files in a build-owned folder that this build no longer produces */
  const stale = [];
  if (fs.existsSync(to)) {
    for (const owned of BUILD_OWNED) {
      const dir = path.join(to, owned);
      if (!fs.existsSync(dir)) continue;
      for (const rel of walk(dir, to)) {
        if (!built.includes(rel)) stale.push(rel);
      }
    }
  }

  const preserved = fs.existsSync(to)
    ? fs.readdirSync(to).filter(f => SACRED.includes(f))
    : [];

  /* homebrew the player imported themselves - kept, and said so */
  const hbDir = path.join(to, 'homebrew');
  const extraHomebrew = fs.existsSync(hbDir)
    ? walk(hbDir, to).filter(rel => !built.includes(rel)).map(rel => rel.replace(/^homebrew\//, ''))
    : [];

  return { name, from, to, fresh: !fs.existsSync(to), add, update, keep, stale,
           preserved, extraHomebrew };
}

function apply(p) {
  fs.mkdirSync(p.to, { recursive: true });
  for (const rel of p.add.concat(p.update)) {
    const src = path.join(p.from, rel);
    const dst = path.join(p.to, rel);
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(src, dst);
  }
  if (PRUNE) {
    for (const rel of p.stale) {
      /* belt and braces: refuse anything that is not inside a folder the build
         owns, whatever computed it */
      const top = rel.split('/')[0];
      if (!BUILD_OWNED.includes(top) || SACRED.includes(top)) continue;
      try { fs.unlinkSync(path.join(p.to, rel)); } catch (e) {}
    }
  }
}

function verify(p) {
  const bad = [];
  for (const rel of walk(p.from)) {
    if (!same(path.join(p.from, rel), path.join(p.to, rel))) bad.push(rel);
  }
  return bad;
}

function main() {
  const dest = findSymbiotesDir();
  if (!dest) {
    console.error('Could not find the TaleSpire Symbiotes folder. Looked in:');
    for (const c of candidates()) console.error('  ' + c);
    console.error('');
    console.error('Pass it directly:  node tools/install-symbiotes.js --to "<path>"');
    console.error('It is the folder that already contains your installed symbiotes.');
    process.exit(1);
  }
  if (!fs.existsSync(DIST)) {
    console.error('No dist/ to install. Run:  node tools/build-symbiote.js');
    process.exit(1);
  }

  console.log('TaleSpire symbiotes: ' + dest);
  console.log(CHECK ? '(checking only - nothing will be written)\n' : '');

  let changedAny = false;
  const plans = [];
  for (const name of SYMBIOTES) {
    const p = plan(name, dest);
    if (p.missingBuild) { console.log(name + ': not built, skipped'); continue; }
    plans.push(p);

    const n = p.add.length + p.update.length;
    if (!n && !(PRUNE && p.stale.length)) {
      console.log(name + ': already up to date (' + p.keep.length + ' files)');
    } else {
      changedAny = true;
      console.log(name + (p.fresh ? ': installing fresh' : ': updating') +
        '  +' + p.add.length + ' new, ' + p.update.length + ' changed, ' +
        p.keep.length + ' unchanged');
      for (const rel of p.add.slice(0, 8)) console.log('    new     ' + rel);
      if (p.add.length > 8) console.log('    new     ... and ' + (p.add.length - 8) + ' more');
      for (const rel of p.update.slice(0, 8)) console.log('    update  ' + rel);
      if (p.update.length > 8) console.log('    update  ... and ' + (p.update.length - 8) + ' more');
    }
    if (p.preserved.length) {
      console.log('    keeping ' + p.preserved.join(', ') + ' untouched');
    }
    if (p.stale.length) {
      console.log('    ' + (PRUNE ? 'pruning ' : 'stale   ') + p.stale.length +
        ' generated file(s) no longer in the build' +
        (PRUNE ? '' : '  (run with --prune to remove)'));
    }
    /* Anything the player put in homebrew/ themselves. Reported so they know it
       is being kept, never removed. */
    if (p.extraHomebrew && p.extraHomebrew.length) {
      console.log('    keeping ' + p.extraHomebrew.length +
        ' homebrew file(s) of your own: ' + p.extraHomebrew.join(', '));
    }
  }

  if (CHECK) {
    console.log('\n' + (changedAny ? 'Out of date - run without --check to install.'
                                   : 'Everything is current.'));
    return;
  }

  for (const p of plans) apply(p);

  let bad = 0;
  for (const p of plans) {
    const wrong = verify(p);
    if (wrong.length) {
      bad += wrong.length;
      console.error('\n' + p.name + ': ' + wrong.length + ' file(s) did not copy correctly:');
      for (const rel of wrong.slice(0, 10)) console.error('    ' + rel);
    }
  }
  if (bad) {
    console.error('\nSomething went wrong. Is TaleSpire holding a file open?');
    process.exit(1);
  }

  console.log('\n' + (changedAny
    ? 'Installed. Reload the symbiote in TaleSpire to pick it up.'
    : 'Nothing to do - already current.'));
  console.log('Your characters, 5etools data and homebrew were left alone.');
}

main();
